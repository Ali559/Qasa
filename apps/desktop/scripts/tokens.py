#!/usr/bin/env python3
"""Write src/theme/tokens.css from the iOS palette (apps/ios/qasa_ios/Theme/Theme.swift).

The iOS app is the design source of truth, so the desktop never hand-copies a color:
change Theme.swift, then run `bun run tokens`. `--check` fails if tokens.css is stale.
"""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

DESKTOP = Path(__file__).resolve().parent.parent
THEME_SWIFT = DESKTOP.parent / "ios/qasa_ios/Theme/Theme.swift"
OUT = DESKTOP / "src/theme/tokens.css"

COLOR_RE = re.compile(r'(\w+):\s*Color\(hex:\s*"([0-9A-Fa-f]{6})"\)')
METRIC_RE = re.compile(r"static let (cornerRadius|cornerRadiusLarge|screenPadding): CGFloat = (\d+)")


def kebab(name: str) -> str:
    return re.sub(r"(?<!^)(?=[A-Z])", "-", name).lower()


def palette(source: str, name: str) -> list[tuple[str, str]]:
    match = re.search(rf"static let {name} = ThemePalette\((.*?)\n    \)", source, re.S)
    if not match:
        raise SystemExit(f"ThemePalette.{name} not found in {THEME_SWIFT}")
    colors = COLOR_RE.findall(match.group(1))
    if not colors:
        raise SystemExit(f"no colors parsed from ThemePalette.{name}")
    return [(kebab(k), f"#{v.upper()}") for k, v in colors]


def render() -> str:
    source = THEME_SWIFT.read_text(encoding="utf-8")
    light = palette(source, "light")
    dark = palette(source, "dark")
    if [k for k, _ in light] != [k for k, _ in dark]:
        raise SystemExit("light and dark palettes have different tokens")
    metrics = {kebab(k): int(v) for k, v in METRIC_RE.findall(source)}

    def block(selector: str, colors: list[tuple[str, str]], scheme: str, indent: str = "") -> list[str]:
        lines = [f"{indent}{selector} {{", f"{indent}  color-scheme: {scheme};"]
        lines += [f"{indent}  --{k}: {v};" for k, v in colors]
        lines.append(f"{indent}}}")
        return lines

    out = [
        "/* Generated by scripts/tokens.py from apps/ios/qasa_ios/Theme/Theme.swift. Do not edit. */",
        "",
        ":root {",
        *[f"  --{k}: {v}px;" for k, v in sorted(metrics.items())],
        "}",
        "",
        *block(':root,\n:root[data-theme="light"]', light, "light"),
        "",
        *block(':root[data-theme="dark"]', dark, "dark"),
        "",
        "@media (prefers-color-scheme: dark) {",
        *block(':root:not([data-theme="light"])', dark, "dark", "  "),
        "}",
        "",
    ]
    return "\n".join(out)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="exit 1 if tokens.css is stale")
    args = parser.parse_args()
    css = render()
    if args.check:
        if not OUT.is_file() or OUT.read_text(encoding="utf-8") != css:
            print("src/theme/tokens.css is stale; run: bun run tokens", file=sys.stderr)
            return 1
        print("tokens.css up to date")
        return 0
    OUT.write_text(css, encoding="utf-8")
    print(f"wrote {OUT.relative_to(DESKTOP)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
