//! Inputs for the golden vectors, and the code that computes their expected outputs.

use serde::{Deserialize, Serialize};

#[derive(Serialize, Deserialize, PartialEq, Debug)]
pub struct Vectors {
    pub comment: String,
    pub pbkdf2_iterations: u32,
    pub kdf: Vec<KdfCase>,
    pub aead: Vec<AeadCase>,
    pub search: SearchVectors,
}

#[derive(Serialize, Deserialize, PartialEq, Debug)]
pub struct KdfCase {
    pub name: String,
    pub password: String,
    pub salt_hex: String,
    pub root_key_hex: String,
    pub verifier_hex: String,
    pub enc_key_hex: String,
    pub search_key_hex: String,
}

#[derive(Serialize, Deserialize, PartialEq, Debug)]
pub struct AeadCase {
    pub name: String,
    pub key_hex: String,
    pub nonce_hex: String,
    pub plaintext: String,
    pub blob_hex: String,
}

#[derive(Serialize, Deserialize, PartialEq, Debug)]
pub struct SearchVectors {
    pub key_hex: String,
    pub cases: Vec<SearchCase>,
}

#[derive(Serialize, Deserialize, PartialEq, Debug)]
pub struct SearchCase {
    pub name: String,
    pub text: String,
    /// Sorted by code point. Platforms compare these as sets.
    pub tokens: Vec<String>,
    pub hashes: Vec<String>,
}

fn seq_salt(start: u8) -> Vec<u8> {
    (0..32u8).map(|i| start.wrapping_add(i)).collect()
}

pub fn build() -> Vectors {
    let kdf_inputs: Vec<(&str, &str, Vec<u8>)> = vec![
        ("ascii", "correct horse battery staple", seq_salt(0)),
        // The password is used exactly as typed: spaces are not trimmed.
        ("surrounding spaces", "  pad me  ", seq_salt(0x20)),
        ("arabic", "كلمة السر ١٢٣", seq_salt(0x40)),
        ("sorani", "وشەی نهێنی", seq_salt(0x60)),
        ("emoji", "🔐qasa", seq_salt(0x80)),
        // Legacy vaults with no stored salt use 32 zero bytes.
        ("legacy zero salt", "legacy-pass", vec![0u8; 32]),
        // The shortest salt iOS accepts.
        ("16-byte salt", "short salt", seq_salt(0xA0)[..16].to_vec()),
    ];

    let mut kdf = Vec::new();
    let mut first_keys = None;
    for (name, password, salt) in kdf_inputs {
        let root = qasa_vault::derive_root_key(password, &salt).unwrap();
        let keys = root.subkeys();
        kdf.push(KdfCase {
            name: name.into(),
            password: password.into(),
            salt_hex: hex::encode(&salt),
            root_key_hex: hex::encode(root.as_bytes()),
            verifier_hex: hex::encode(root.verifier()),
            enc_key_hex: hex::encode(keys.enc()),
            search_key_hex: hex::encode(keys.search()),
        });
        if first_keys.is_none() {
            first_keys = Some((*keys.enc(), *keys.search()));
        }
    }
    let (enc_key, search_key) = first_keys.unwrap();

    let aead_inputs = [
        ("envelope", r#"{"displayName":"GitHub","subtitle":"dev"}"#),
        ("empty", ""),
        ("unicode payload", r#"{"note":"سڵاو، مرحبا 🔐"}"#),
    ];
    let aead = aead_inputs
        .iter()
        .enumerate()
        .map(|(i, (name, plaintext))| {
            let nonce: [u8; 12] = std::array::from_fn(|j| (i as u8) * 16 + j as u8);
            AeadCase {
                name: (*name).into(),
                key_hex: hex::encode(enc_key),
                nonce_hex: hex::encode(nonce),
                plaintext: (*plaintext).into(),
                blob_hex: hex::encode(qasa_vault::encrypt_with_nonce(
                    plaintext.as_bytes(),
                    &enc_key,
                    &nonce,
                )),
            }
        })
        .collect();

    let search_inputs = [
        ("single letter", "A"),
        ("ascii login", "GitHub dev@qasa.io"),
        ("digits and punctuation", "X-1 2026"),
        ("latin accents", "Café Ñandú"),
        ("arabic", "حسابي المصرفي"),
        ("arabic with harakat", "مُحَمَّد"),
        ("arabic-indic digits", "رمز ١٢٣٤"),
        ("sorani", "فەیسبووک"),
        // ZWNJ (U+200C) is not a letter, so it splits the word, as on iOS.
        ("sorani with zwnj", "ئیمەیڵ\u{200C}ی سەرەکی"),
        ("mixed scripts", "Asiacell ئاسیاسێڵ"),
    ];
    let cases = search_inputs
        .iter()
        .map(|(name, text)| SearchCase {
            name: (*name).into(),
            text: (*text).into(),
            tokens: qasa_vault::tokenize(text),
            hashes: qasa_vault::token_hashes(text, &search_key),
        })
        .collect();

    Vectors {
        comment: "Golden vectors for the Qasa vault. Generated by core/qasa-vault/examples/gen_vectors.rs; checked by core (cargo test), iOS (qasaTests/CoreVectorTests.swift) and Android (vault/crypto/CoreVectorTest.kt). Do not edit by hand.".into(),
        pbkdf2_iterations: qasa_vault::PBKDF2_ITERATIONS,
        kdf,
        aead,
        search: SearchVectors { key_hex: hex::encode(search_key), cases },
    }
}
