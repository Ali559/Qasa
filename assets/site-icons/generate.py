#!/usr/bin/env python3
"""Generate each platform's bundled site icons from assets/site-icons/sites.json.

    python3 assets/site-icons/generate.py          # write the outputs
    python3 assets/site-icons/generate.py --check  # exit 1 if any output is stale

Outputs (committed; do not hand-edit):
  - Android: apps/android/.../theme/SiteIconData.kt (path data + domain table)
  - iOS:     apps/ios/qasa_ios/Assets.xcassets/SiteIcons/ (template SVG imagesets)
             apps/ios/qasa_ios/Components/SiteIconData.swift (domain table)
  - Desktop and extension: apps/desktop/src/vault/siteIconData.ts (paths + domains)
"""

from __future__ import annotations

import argparse
import json
import re
import shutil
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent.parent
SITES = HERE / "sites.json"

ANDROID_KT = ROOT / "apps/android/app/src/main/java/alibarznji/qasa/theme/SiteIconData.kt"
IOS_ASSETS = ROOT / "apps/ios/qasa_ios/Assets.xcassets/SiteIcons"
IOS_SWIFT = ROOT / "apps/ios/qasa_ios/Components/SiteIconData.swift"
WEB_TS = ROOT / "apps/desktop/src/vault/siteIconData.ts"

HEADER = "Generated by assets/site-icons/generate.py from sites.json. Do not edit."
ID_RE = re.compile(r"^[a-z0-9]+$")
DOMAIN_RE = re.compile(r"^[a-z0-9-]+(\.[a-z0-9-]+)+$")
PATH_RE = re.compile(r"^[MmZzLlHhVvCcSsQqTtAaEe0-9.,\- ]+$")


def load() -> list[dict]:
    sites = json.loads(SITES.read_text())["sites"]
    seen_ids: set[str] = set()
    seen_domains: dict[str, str] = {}
    for site in sites:
        sid = site["id"]
        if not ID_RE.match(sid) or sid in seen_ids:
            sys.exit(f"sites.json: bad or duplicate id {sid!r}")
        seen_ids.add(sid)
        if not site.get("path") or not PATH_RE.match(site["path"]):
            sys.exit(f"sites.json: {sid} has no usable path")
        if not site.get("domains"):
            sys.exit(f"sites.json: {sid} has no domains")
        for domain in site["domains"]:
            if not DOMAIN_RE.match(domain) or domain.startswith("www."):
                sys.exit(f"sites.json: {sid} has a bad domain {domain!r}")
            if domain in seen_domains:
                sys.exit(f"sites.json: {domain} is listed by {seen_domains[domain]} and {sid}")
            seen_domains[domain] = sid
    return sites


def domain_pairs(sites: list[dict]) -> list[tuple[str, str]]:
    return sorted((d, s["id"]) for s in sites for d in s["domains"])


def android(sites: list[dict]) -> str:
    paths = "\n".join(f'        "{s["id"]}" to "{s["path"]}",' for s in sites)
    domains = "\n".join(f'        "{d}" to "{i}",' for d, i in domain_pairs(sites))
    return f"""// {HEADER}
package alibarznji.qasa.theme

/** Bundled site icons (Simple Icons, 24x24 viewport): one SVG path per icon id. */
internal object SiteIconData {{
    val paths: Map<String, String> = mapOf(
{paths}
    )

    /** Registrable domain → icon id. */
    val domains: Map<String, String> = mapOf(
{domains}
    )
}}
"""


def swift(sites: list[dict]) -> str:
    domains = "\n".join(f'        "{d}": "{i}",' for d, i in domain_pairs(sites))
    return f"""// {HEADER}

/// Registrable domain → icon id. Each id has a template image `site-<id>` in
/// `Assets.xcassets/SiteIcons`.
enum SiteIconData {{
    static let domains: [String: String] = [
{domains}
    ]
}}
"""


def typescript(sites: list[dict]) -> str:
    paths = "\n".join(f"  {json.dumps(s['id'])}: {json.dumps(s['path'])}," for s in sites)
    domains = "\n".join(f"  {json.dumps(d)}: {json.dumps(i)}," for d, i in domain_pairs(sites))
    return f"""// {HEADER}

/** Bundled site icons (Simple Icons, 24x24 viewBox): one SVG path per icon id. */
export const SITE_ICON_PATHS: Record<string, string> = {{
{paths}
}}

/** Registrable domain → icon id. */
export const SITE_ICON_DOMAINS: Record<string, string> = {{
{domains}
}}
"""


def ios_assets(sites: list[dict]) -> dict[Path, str]:
    info = {"info": {"author": "xcode", "version": 1}}
    files = {IOS_ASSETS / "Contents.json": json.dumps(info, indent=2) + "\n"}
    for s in sites:
        name = f"site-{s['id']}"
        folder = IOS_ASSETS / f"{name}.imageset"
        contents = {
            "images": [{"filename": f"{name}.svg", "idiom": "universal"}],
            **info,
            "properties": {"preserves-vector-representation": True, "template-rendering-intent": "template"},
        }
        files[folder / "Contents.json"] = json.dumps(contents, indent=2) + "\n"
        files[folder / f"{name}.svg"] = (
            f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24"><path d="{s["path"]}"/></svg>\n'
        )
    return files


def outputs(sites: list[dict]) -> dict[Path, str]:
    return {
        ANDROID_KT: android(sites),
        IOS_SWIFT: swift(sites),
        WEB_TS: typescript(sites),
        **ios_assets(sites),
    }


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--check", action="store_true", help="exit 1 if generated files are stale")
    args = parser.parse_args()
    files = outputs(load())
    existing = {p for p in IOS_ASSETS.rglob("*") if p.is_file()} if IOS_ASSETS.exists() else set()
    stale_assets = existing - set(files)

    if args.check:
        stale = [p for p, text in files.items() if not p.exists() or p.read_text() != text]
        stale += sorted(stale_assets)
        for p in stale:
            print(f"stale: {p.relative_to(ROOT)}", file=sys.stderr)
        return 1 if stale else 0

    if IOS_ASSETS.exists():
        shutil.rmtree(IOS_ASSETS)
    for path, text in files.items():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text)
    print(f"{len(files)} files written")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
