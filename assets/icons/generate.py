#!/usr/bin/env python3
"""Write every app's icons from assets/icons/svg/ (one library, design/README.md "Icons").

    python3 assets/icons/generate.py          # write the outputs
    python3 assets/icons/generate.py --check  # exit 1 if any output is stale (CI)

Outputs (committed; never edit them by hand):
  - iOS (app and extensions): apps/ios/SharedAutofill/QasaIcons.xcassets (template SVGs)
    and apps/ios/SharedAutofill/QasaIcon.swift (`QasaIcon` names, `QasaIconImage`)
  - Android: apps/android/.../theme/QasaIcons.kt (`QasaIcons.Home`, … as ImageVectors)
  - Desktop and extension: apps/desktop/src/icons/qasaIcons.ts (for `QasaIcon.vue`)

Icon names come from icons.json; `<name>.fill` is the filled glyph a navigation tab shows
while it is the active tab.
"""

from __future__ import annotations

import argparse
import json
import re
import shutil
import sys
import xml.etree.ElementTree as ET
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent.parent
SVG_DIR = HERE / "svg"
MANIFEST = HERE / "icons.json"

IOS_ASSETS = ROOT / "apps/ios/SharedAutofill/QasaIcons.xcassets"
IOS_SWIFT = ROOT / "apps/ios/SharedAutofill/QasaIcon.swift"
ANDROID_KT = ROOT / "apps/android/app/src/main/java/alibarznji/qasa/theme/QasaIcons.kt"
WEB_TS = ROOT / "apps/desktop/src/icons/qasaIcons.ts"

HEADER = "Generated by assets/icons/generate.py from assets/icons. Do not edit."
NS = "{http://www.w3.org/2000/svg}"
NUM = r"-?\d*\.?\d+(?:e-?\d+)?"


# MARK: - Reading the SVGs

class Shape:
    """One drawn element, as path data plus its resolved paint."""

    def __init__(self, d: str, fill: bool, stroke: float, cap: str, join: str, even_odd: bool):
        self.d, self.fill, self.stroke, self.cap, self.join, self.even_odd = d, fill, stroke, cap, join, even_odd


def circle_d(cx: float, cy: float, rx: float, ry: float) -> str:
    return (f"M{fmt(cx - rx)} {fmt(cy)}A{fmt(rx)} {fmt(ry)} 0 1 0 {fmt(cx + rx)} {fmt(cy)}"
            f"A{fmt(rx)} {fmt(ry)} 0 1 0 {fmt(cx - rx)} {fmt(cy)}Z")


def fmt(v: float) -> str:
    return str(int(v)) if float(v).is_integer() else f"{v:.4f}".rstrip("0").rstrip(".")


def read_glyph(path: Path) -> tuple[float, float, list[Shape]]:
    root = ET.fromstring(path.read_text())
    vb = [float(x) for x in root.get("viewBox", "0 0 24 24").split()]
    if vb[0] or vb[1]:
        sys.exit(f"{path.name}: viewBox must start at 0 0")
    shapes: list[Shape] = []

    def walk(el: ET.Element, style: dict) -> None:
        style = dict(style)
        for key in ("fill", "stroke", "stroke-width", "stroke-linecap", "stroke-linejoin", "fill-rule"):
            if el.get(key) is not None:
                style[key] = el.get(key)
        if el.get("transform"):
            sys.exit(f"{path.name}: transforms are not supported")
        tag = el.tag.replace(NS, "")
        if tag == "path":
            d = el.get("d")
        elif tag == "circle":
            r = float(el.get("r"))
            d = circle_d(float(el.get("cx", 0)), float(el.get("cy", 0)), r, r)
        elif tag == "ellipse":
            d = circle_d(float(el.get("cx", 0)), float(el.get("cy", 0)), float(el.get("rx")), float(el.get("ry")))
        elif tag in ("svg", "g"):
            d = None
        else:
            sys.exit(f"{path.name}: <{tag}> is not supported")
        if d:
            fill = style.get("fill", "currentColor") not in ("none",)
            stroked = style.get("stroke", "none") not in ("none",)
            shapes.append(Shape(
                d=re.sub(r"\s+", " ", d).strip(),
                fill=fill,
                stroke=float(style.get("stroke-width", 1)) if stroked else 0.0,
                cap=style.get("stroke-linecap", "butt"),
                join=style.get("stroke-linejoin", "miter"),
                even_odd=style.get("fill-rule") == "evenodd",
            ))
        for child in el:
            walk(child, style)

    walk(root, {})
    if not shapes:
        sys.exit(f"{path.name}: no shapes")
    return vb[2], vb[3], shapes


BASES: dict[str, float] = {}


def load() -> dict[str, tuple[float, float, list[Shape], str]]:
    manifest = json.loads(MANIFEST.read_text())["icons"]
    glyphs: dict[str, tuple[float, float, list[Shape], str]] = {}
    for name, spec in manifest.items():
        if not re.fullmatch(r"[a-z][a-z0-9-]*", name):
            sys.exit(f"icons.json: bad name {name!r}")
        files = [(name, SVG_DIR / f"{name}.svg")]
        if spec.get("fill"):
            files.append((f"{name}.fill", SVG_DIR / f"{name}.fill.svg"))
        for key, file in files:
            if not file.exists():
                sys.exit(f"{file.name} is missing: run import_solar.py")
            w, h, shapes = read_glyph(file)
            glyphs[key] = (w, h, shapes, file.read_text())
            # The point size the glyph's frame is drawn for: 24 for the 24x24 glyphs, the SF
            # Symbol size for the measured chevrons (back 17, forward and down 13).
            BASES[key] = float(spec.get("base", 24))
    return glyphs


def camel(name: str) -> str:
    parts = re.split(r"[-.]", name)
    return parts[0] + "".join(p[:1].upper() + p[1:] for p in parts[1:])


def pascal(name: str) -> str:
    c = camel(name)
    return c[:1].upper() + c[1:]


# MARK: - iOS

SWIFT_KEYWORDS = {"import", "default", "case", "class", "struct", "enum", "func", "var", "let",
                  "in", "is", "as", "return", "self", "protocol", "extension", "init", "private",
                  "public", "internal", "static", "where", "while", "for", "if", "else", "switch",
                  "repeat", "do", "try", "throw", "catch", "nil", "true", "false", "operator"}


def swift_name(key: str) -> str:
    name = camel(key)
    return f"`{name}`" if name in SWIFT_KEYWORDS else name


def ios(glyphs) -> dict[Path, str]:
    info = {"info": {"author": "xcode", "version": 1}}
    files = {IOS_ASSETS / "Contents.json": json.dumps(info, indent=2) + "\n"}
    for key, (_w, _h, _shapes, svg) in glyphs.items():
        asset = f"qasa-{key.replace('.', '-')}"
        folder = IOS_ASSETS / f"{asset}.imageset"
        files[folder / "Contents.json"] = json.dumps({
            "images": [{"filename": f"{asset}.svg", "idiom": "universal"}],
            **info,
            "properties": {"preserves-vector-representation": True, "template-rendering-intent": "template"},
        }, indent=2) + "\n"
        # Asset catalogs draw template images from their alpha: any solid colour works.
        files[folder / f"{asset}.svg"] = svg.replace("currentColor", "#000000")
    cases = "\n".join(
        f'    case {swift_name(k)} = "qasa-{k.replace(".", "-")}"' for k in glyphs
    )
    sizes = "\n".join(
        f"        case .{swift_name(k)}: return CGSize(width: {fmt(w)}, height: {fmt(h)})"
        for k, (w, h, _s, _v) in glyphs.items() if (w, h) != (24, 24)
    )
    bases = "\n".join(
        f"        case .{swift_name(k)}: return {fmt(BASES[k])}" for k in glyphs if BASES[k] != 24
    )
    files[IOS_SWIFT] = f'''// {HEADER}
// swiftlint:disable all

import SwiftUI

/// Every icon the apps show: Solar Linear (CC BY 4.0, 480 Design), plus the filled glyph
/// (`…Fill`) a navigation tab shows while active. Android (`QasaIcons`) and the desktop
/// (`QasaIcon.vue`) draw the same files. Draw one with `QasaIconImage(.copy, size: 16)`.
enum QasaIcon: String, CaseIterable {{
{cases}

    /// The glyph's own frame in points (24x24 unless listed): the chevrons keep the SF
    /// Symbol frames they were measured from.
    var frame: CGSize {{
        switch self {{
{sizes}
        default: return CGSize(width: 24, height: 24)
        }}
    }}

    /// The point size `frame` is drawn for: 24, except the chevrons, which were measured
    /// at their SF Symbol sizes (back 17, forward and down 13).
    var basePointSize: CGFloat {{
        switch self {{
{bases}
        default: return 24
        }}
    }}
}}

/// One icon at `size` points, tinted with the foreground colour. For the chevrons `size` is
/// the SF Symbol point size they replace: `.chevronBack` at 17 draws its 13x18 frame.
struct QasaIconImage: View {{
    let icon: QasaIcon
    var size: CGFloat = 24

    init(_ icon: QasaIcon, size: CGFloat = 24) {{
        self.icon = icon
        self.size = size
    }}

    var body: some View {{
        let scale = size / icon.basePointSize
        Image(icon.rawValue)
            .renderingMode(.template)
            .resizable()
            .frame(width: icon.frame.width * scale, height: icon.frame.height * scale)
            .accessibilityHidden(true)
    }}
}}
'''
    return files


# MARK: - Android

CAP = {"butt": "StrokeCap.Butt", "round": "StrokeCap.Round", "square": "StrokeCap.Square"}
JOIN = {"miter": "StrokeJoin.Miter", "round": "StrokeJoin.Round", "bevel": "StrokeJoin.Bevel"}


def android(glyphs) -> str:
    vals = []
    for key, (w, h, shapes, _svg) in glyphs.items():
        shape_lines = []
        for s in shapes:
            args = [json.dumps(s.d), f"fill = {str(s.fill).lower()}"]
            if s.stroke:
                args += [f"stroke = {fmt(s.stroke)}f", f"cap = {CAP[s.cap]}", f"join = {JOIN[s.join]}"]
            if s.even_odd:
                args.append("evenOdd = true")
            shape_lines.append(f"            S({', '.join(args)}),")
        vals.append(
            f'    val {pascal(key)}: ImageVector by lazy {{\n'
            f'        icon("{key}", {fmt(w)}f, {fmt(h)}f,\n' + "\n".join(shape_lines) + "\n        )\n    }\n"
        )
    return f'''// {HEADER}
@file:Suppress("MagicNumber", "ktlint")

package alibarznji.qasa.theme

import androidx.compose.ui.graphics.Color
import androidx.compose.ui.graphics.PathFillType
import androidx.compose.ui.graphics.SolidColor
import androidx.compose.ui.graphics.StrokeCap
import androidx.compose.ui.graphics.StrokeJoin
import androidx.compose.ui.graphics.vector.ImageVector
import androidx.compose.ui.graphics.vector.addPathNodes
import androidx.compose.ui.unit.dp

/**
 * Every icon the apps show: Solar Linear (CC BY 4.0, 480 Design), plus the filled glyph
 * (`…Fill`) a navigation tab shows while active. iOS (`QasaIcon`) and the desktop
 * (`QasaIcon.vue`) draw the same files. Draw with `QasaIcon(QasaIcons.Copy, size = 16.dp)`
 * or `Icon(QasaIcons.Copy, …)`; the glyph is 24dp (the chevrons keep their iOS frames).
 */
object QasaIcons {{
{chr(10).join(vals)}
    private class S(
        val d: String,
        val fill: Boolean,
        val stroke: Float = 0f,
        val cap: StrokeCap = StrokeCap.Butt,
        val join: StrokeJoin = StrokeJoin.Miter,
        val evenOdd: Boolean = false,
    )

    private fun icon(name: String, width: Float, height: Float, vararg shapes: S): ImageVector {{
        val builder = ImageVector.Builder(
            name = name,
            defaultWidth = width.dp,
            defaultHeight = height.dp,
            viewportWidth = width,
            viewportHeight = height,
            // Black here; `Icon(tint = …)` recolours the whole glyph.
            autoMirror = name.startsWith("chevron"),
        )
        for (s in shapes) {{
            builder.addPath(
                pathData = addPathNodes(s.d),
                pathFillType = if (s.evenOdd) PathFillType.EvenOdd else PathFillType.NonZero,
                fill = if (s.fill) SolidColor(Color.Black) else null,
                stroke = if (s.stroke > 0f) SolidColor(Color.Black) else null,
                strokeLineWidth = s.stroke,
                strokeLineCap = s.cap,
                strokeLineJoin = s.join,
            )
        }}
        return builder.build()
    }}
}}
'''


# MARK: - Web

def web(glyphs) -> str:
    rows = []
    for key, (w, h, _shapes, svg) in glyphs.items():
        inner = re.sub(r"^<svg[^>]*>|</svg>\s*$", "", svg.strip())
        rows.append(f"  {json.dumps(key)}: {{ w: {fmt(w)}, h: {fmt(h)}, base: {fmt(BASES[key])}, body: {json.dumps(inner)} }},")
    names = " | ".join(json.dumps(k) for k in glyphs)
    return f"""// {HEADER}

/**
 * Every icon the apps show: Solar Linear (CC BY 4.0, 480 Design), plus the filled glyph
 * (`….fill`) a navigation tab shows while active. iOS (`QasaIcon`) and Android
 * (`QasaIcons`) draw the same files. Use `<QasaIcon name="copy" :size="16" />`.
 */
export type QasaIconName = {names}

export interface QasaIconGlyph {{
  /** The glyph's frame: 24x24, except the chevrons, which keep their iOS frames. */
  w: number
  h: number
  /** The point size the frame is drawn for: 24, or the chevrons' SF Symbol size (17 / 13). */
  base: number
  /** SVG markup inside the `<svg>`, drawn in `currentColor`. */
  body: string
}}

export const QASA_ICONS: Record<QasaIconName, QasaIconGlyph> = {{
{chr(10).join(rows)}
}}
"""


# MARK: - Main

def outputs(glyphs) -> dict[Path, str]:
    return {**ios(glyphs), ANDROID_KT: android(glyphs), WEB_TS: web(glyphs)}


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--check", action="store_true", help="exit 1 if a generated file is stale")
    args = parser.parse_args()
    files = outputs(load())
    existing = {p for p in IOS_ASSETS.rglob("*") if p.is_file()} if IOS_ASSETS.exists() else set()
    stale_assets = existing - set(files)
    changed = [p for p, text in files.items() if not p.exists() or p.read_text() != text]
    if args.check:
        bad = changed + sorted(stale_assets)
        for p in bad:
            print(f"stale: {p.relative_to(ROOT)}", file=sys.stderr)
        if bad:
            print("run: python3 assets/icons/generate.py", file=sys.stderr)
            return 1
        print("icons up to date")
        return 0
    for p in stale_assets:
        p.unlink()
    for folder in sorted({p.parent for p in stale_assets}, reverse=True):
        if folder.exists() and not any(folder.iterdir()):
            shutil.rmtree(folder)
    for p in changed:
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text(files[p])
    print(f"{len(changed)} file(s) written, {len(stale_assets)} removed")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
