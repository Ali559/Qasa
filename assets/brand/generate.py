#!/usr/bin/env python3
"""Qasa brand mark, the Qaf Keyhole: one letter that is a Latin Q, an Arabic qaf (the two
dots) and a lock (the keyhole in the bowl). See docs/design.md and the logo research page.

The geometry lives here once, on a 200-unit grid, and this script writes every icon and
mark the apps ship. Run it after changing the shapes or the colours:

    python3 assets/brand/generate.py

then rebuild the desktop icon set (`cd apps/desktop && bun run icons`). Needs Pillow.
"""

from __future__ import annotations

import json
from pathlib import Path

from PIL import Image, ImageDraw

ROOT = Path(__file__).resolve().parents[2]
BRAND = ROOT / "assets/brand"

# Brand palette (apps/ios/qasa_ios/Theme/Theme.swift is the source for app UI colours).
PURPLE = "#722F99"
BEIGE = "#FEE7C8"
PEACH = "#FF9292"
DARK_BG = "#17111D"
LAVENDER = "#B67FDB"

# --- Geometry, on the 200-unit grid ------------------------------------------------------
DOTS = [(86, 42, 10), (114, 42, 10)]          # the qaf's two dots (cx, cy, r)
RING = (100, 112, 44, 18)                      # bowl: cx, cy, r, stroke width
TAIL = ((121, 133), (156, 168), 16)            # the Q's tail, crossing the bowl like a Q
                                               # (not leaving its edge like a magnifier)
KEY_HOLE = (100, 100, 11)                      # keyhole head (cx, cy, r)
KEY_SLOT = [(93, 105), (107, 105), (110, 125), (90, 125)]
# The glyph's box is x 47..163, y 32..177; this shift centres it on (100, 100).
CENTRE_SHIFT = (-5.0, -4.5)
# Glyph scale inside the rounded app tile (about 62% of its height).
TILE_SCALE = 0.85


def transform(scale: float):
    """Centre the glyph, then scale it about the middle of the 200 grid."""
    dx, dy = CENTRE_SHIFT

    def t(x: float, y: float) -> tuple[float, float]:
        return (100 + scale * (x + dx - 100), 100 + scale * (y + dy - 100))

    return t


# --- SVG ---------------------------------------------------------------------------------
def svg_glyph(mark: str, hole: str, scale: float) -> str:
    dx, dy = CENTRE_SHIFT
    g = f'<g transform="translate(100 100) scale({scale}) translate({-100 + dx} {-100 + dy})">'
    for cx, cy, r in DOTS:
        g += f'<circle cx="{cx}" cy="{cy}" r="{r}" fill="{mark}"/>'
    cx, cy, r, w = RING
    g += f'<circle cx="{cx}" cy="{cy}" r="{r}" fill="none" stroke="{mark}" stroke-width="{w}"/>'
    (x1, y1), (x2, y2), w = TAIL
    g += f'<path d="M{x1} {y1} L{x2} {y2}" stroke="{mark}" stroke-width="{w}" stroke-linecap="round"/>'
    cx, cy, r = KEY_HOLE
    g += f'<circle cx="{cx}" cy="{cy}" r="{r}" fill="{hole}"/>'
    pts = " ".join(f"{x},{y}" for x, y in KEY_SLOT)
    g += f'<polygon points="{pts}" fill="{hole}"/>'
    return g + "</g>"


def svg_tile(bg: str = PURPLE, mark: str = BEIGE, hole: str = PEACH, radius: int = 44) -> str:
    return (
        '<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 200 200">'
        f'<rect width="200" height="200" rx="{radius}" fill="{bg}"/>'
        f"{svg_glyph(mark, hole, TILE_SCALE)}</svg>\n"
    )


def svg_mark(color: str = "#000000") -> str:
    """The bare glyph, one colour, for headers and template images."""
    return (
        '<svg xmlns="http://www.w3.org/2000/svg" viewBox="25 25 150 150">'
        f"{svg_glyph(color, color, 1.0)}</svg>\n"
    )


def ts_mark_module() -> str:
    """The mark as data for the web apps (desktop components and the extension's in-page
    menu build it with DOM calls, so pages with Trusted Types don't interfere)."""
    dx, dy = CENTRE_SHIFT
    c = "currentColor"
    shapes = [("circle", {"cx": cx, "cy": cy, "r": r, "fill": c}) for cx, cy, r in DOTS]
    cx, cy, r, w = RING
    shapes.append(("circle", {"cx": cx, "cy": cy, "r": r, "fill": "none", "stroke": c, "stroke-width": w}))
    (x1, y1), (x2, y2), w = TAIL
    shapes.append(("path", {"d": f"M{x1} {y1} L{x2} {y2}", "stroke": c, "stroke-width": w,
                            "stroke-linecap": "round"}))
    cx, cy, r = KEY_HOLE
    shapes.append(("circle", {"cx": cx, "cy": cy, "r": r, "fill": c}))
    shapes.append(("polygon", {"points": " ".join(f"{x},{y}" for x, y in KEY_SLOT), "fill": c}))
    rows = ",\n".join(
        "  { tag: '%s', attrs: { %s } }" % (tag, ", ".join(f"'{k}': '{v}'" for k, v in attrs.items()))
        for tag, attrs in shapes
    )
    return (
        "// The Qasa mark (Qaf Keyhole). Generated by assets/brand/generate.py; do not edit.\n\n"
        "export interface MarkShape {\n  tag: 'circle' | 'path' | 'polygon'\n  attrs: Record<string, string>\n}\n\n"
        "export const QASA_MARK_VIEWBOX = '25 25 150 150'\n"
        f"export const QASA_MARK_TRANSFORM = 'translate({-100 + dx + 100} {-100 + dy + 100})'\n\n"
        f"export const QASA_MARK_SHAPES: MarkShape[] = [\n{rows},\n]\n"
    )


# --- Raster ------------------------------------------------------------------------------
def raster(size: int, bg: str | None, mark: str, hole: str, scale: float,
           radius: float | None = None, supersample: int = 4) -> Image.Image:
    """Draw the tile at `size` px. `radius` is in 200-grid units; None = full-bleed square."""
    s = size * supersample
    k = s / 200
    img = Image.new("RGBA", (s, s), (0, 0, 0, 0))
    d = ImageDraw.Draw(img)
    if bg:
        if radius is None:
            d.rectangle((0, 0, s, s), fill=bg)
        else:
            d.rounded_rectangle((0, 0, s - 1, s - 1), radius * k, fill=bg)
    t = transform(scale)
    u = k * scale  # grid units -> pixels for lengths

    def disc(cx, cy, r, fill):
        x, y = t(cx, cy)
        d.ellipse((x * k - r * u, y * k - r * u, x * k + r * u, y * k + r * u), fill=fill)

    for cx, cy, r in DOTS:
        disc(cx, cy, r, mark)
    cx, cy, r, w = RING
    x, y = t(cx, cy)
    outer = r + w / 2
    d.ellipse((x * k - outer * u, y * k - outer * u, x * k + outer * u, y * k + outer * u),
              outline=mark, width=round(w * u))
    (x1, y1), (x2, y2), w = TAIL
    a, b = t(x1, y1), t(x2, y2)
    d.line((a[0] * k, a[1] * k, b[0] * k, b[1] * k), fill=mark, width=round(w * u))
    for px, py in ((x1, y1), (x2, y2)):
        disc(px, py, w / 2, mark)
    cx, cy, r = KEY_HOLE
    disc(cx, cy, r, hole)
    d.polygon([(t(x, y)[0] * k, t(x, y)[1] * k) for x, y in KEY_SLOT], fill=hole)
    return img.resize((size, size), Image.LANCZOS)


# --- Android vector drawables ------------------------------------------------------------
def android_paths(mark: str, hole: str) -> str:
    def circle(cx, cy, r):
        return f"M{cx - r},{cy} a{r},{r} 0 1,0 {2 * r},0 a{r},{r} 0 1,0 {-2 * r},0"

    p = ""
    for cx, cy, r in DOTS:
        p += f'        <path android:fillColor="{mark}" android:pathData="{circle(cx, cy, r)}" />\n'
    cx, cy, r, w = RING
    p += (f'        <path android:strokeColor="{mark}" android:strokeWidth="{w}" '
          f'android:fillColor="#00000000" android:pathData="{circle(cx, cy, r)}" />\n')
    (x1, y1), (x2, y2), w = TAIL
    p += (f'        <path android:strokeColor="{mark}" android:strokeWidth="{w}" '
          f'android:strokeLineCap="round" android:pathData="M{x1},{y1} L{x2},{y2}" />\n')
    cx, cy, r = KEY_HOLE
    p += f'        <path android:fillColor="{hole}" android:pathData="{circle(cx, cy, r)}" />\n'
    slot = " L".join(f"{x},{y}" for x, y in KEY_SLOT)
    p += f'        <path android:fillColor="{hole}" android:pathData="M{slot} Z" />\n'
    return p


def android_vector(size_dp: int, viewport: int, group_attrs: str, mark: str, hole: str,
                   comment: str) -> str:
    return (
        '<?xml version="1.0" encoding="utf-8"?>\n'
        f"<!-- {comment} Generated by assets/brand/generate.py; do not edit. -->\n"
        '<vector xmlns:android="http://schemas.android.com/apk/res/android"\n'
        f'    android:width="{size_dp}dp"\n    android:height="{size_dp}dp"\n'
        f'    android:viewportWidth="{viewport}"\n    android:viewportHeight="{viewport}">\n'
        f"    <group {group_attrs}>\n{android_paths(mark, hole)}    </group>\n</vector>\n"
    )


def centred_group(scale: float, pivot: float = 100) -> str:
    dx, dy = CENTRE_SHIFT
    return (f'android:pivotX="{pivot}" android:pivotY="{pivot}" android:scaleX="{scale}" '
            f'android:scaleY="{scale}" android:translateX="{round(scale * dx, 3)}" '
            f'android:translateY="{round(scale * dy, 3)}"')


# --- Write everything --------------------------------------------------------------------
def write(path: Path, data: str | Image.Image) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    if isinstance(data, Image.Image):
        data.save(path)
    else:
        path.write_text(data)
    print(f"wrote {path.relative_to(ROOT)}")


def main() -> None:
    # Masters.
    write(BRAND / "qasa-icon.svg", svg_tile())
    write(BRAND / "qasa-icon-dark.svg", svg_tile(bg=DARK_BG, mark=LAVENDER))
    write(BRAND / "qasa-mark.svg", svg_mark())
    write(BRAND / "qasa-icon-1024.png", raster(1024, PURPLE, BEIGE, PEACH, TILE_SCALE, radius=44))

    # iOS: full-bleed squares (iOS applies its own mask); dark and tinted variants.
    ios = ROOT / "apps/ios/qasa_ios/Assets.xcassets/AppIcon.appiconset"
    write(ios / "AppIcon.png", raster(1024, PURPLE, BEIGE, PEACH, TILE_SCALE).convert("RGB"))
    write(ios / "AppIcon-Dark.png", raster(1024, DARK_BG, LAVENDER, PEACH, TILE_SCALE).convert("RGB"))
    write(ios / "AppIcon-Tinted.png", raster(1024, "#000000", "#FFFFFF", "#9A9A9A", TILE_SCALE).convert("RGB"))
    # In-app mark as a vector template image (tinted by SwiftUI).
    mark_set = ROOT / "apps/ios/qasa_ios/Assets.xcassets/QasaMark.imageset"
    write(mark_set / "QasaMark.svg", svg_mark())
    write(mark_set / "Contents.json", json.dumps({
        "images": [{"filename": "QasaMark.svg", "idiom": "universal"}],
        "info": {"author": "xcode", "version": 1},
        "properties": {"preserves-vector-representation": True, "template-rendering-intent": "template"},
    }, indent=2) + "\n")

    # Android: adaptive-icon foreground (glyph inside the 66dp safe zone), monochrome reuses
    # it; the notification icon and the in-app mark are the bare glyph, tinted at runtime.
    res = ROOT / "apps/android/app/src/main/res/drawable"
    fg_group = f'android:scaleX="0.54" android:scaleY="0.54"><group {centred_group(0.62)}'
    write(res / "ic_launcher_foreground.xml", android_vector(
        108, 108, fg_group, BEIGE, PEACH,
        "Qaf Keyhole launcher foreground, inside the 66dp safe zone.",
    ).replace("    </group>\n</vector>", "    </group></group>\n</vector>"))
    mark_group = 'android:translateX="-25" android:translateY="-25"><group ' + centred_group(1.0)
    for name, comment in (("ic_notification.xml", "Status-bar icon: white silhouette."),
                          ("ic_qasa_mark.xml", "In-app brand mark; tint it with the accent.")):
        write(res / name, android_vector(
            24, 150, mark_group, "#FFFFFF", "#FFFFFF", comment,
        ).replace("    </group>\n</vector>", "    </group></group>\n</vector>"))

    # Browser extension toolbar icons: the rounded tile.
    ext = ROOT / "apps/extension/static/icons"
    for px in (16, 32, 48, 128):
        write(ext / f"icon-{px}.png", raster(px, PURPLE, BEIGE, PEACH, TILE_SCALE, radius=44,
                                             supersample=8 if px < 48 else 4))

    # The mark as data for the desktop app and the browser extension.
    write(ROOT / "apps/desktop/src/brand/qasaMark.ts", ts_mark_module())

    # Web favicons.
    for site in ("apps/landing/public/favicon.svg", "apps/dashboard/public/favicon.svg"):
        write(ROOT / site, svg_tile())
    write(ROOT / "apps/landing/public/qasa-mark.svg", svg_mark(PURPLE))
    write(ROOT / "apps/landing/public/apple-touch-icon.png",
          raster(180, PURPLE, BEIGE, PEACH, TILE_SCALE).convert("RGB"))


if __name__ == "__main__":
    main()
