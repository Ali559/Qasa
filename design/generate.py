#!/usr/bin/env python3
"""Write every app's design tokens from design/tokens.json.

Outputs (all generated, never edit them by hand):
  apps/ios/SharedAutofill/QasaTokens.swift          app + AutoFill + payment extensions
  apps/ios/qasa_ios/Theme/ThemePalette+Tokens.swift the app's ThemePalette.light / .dark
  apps/android/app/src/main/java/alibarznji/qasa/theme/QasaTokens.kt
  apps/desktop/src/theme/tokens.css                 desktop app and browser extension

`--check` exits 1 when any output is stale (CI and `make check`).
"""

from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SPEC = ROOT / "design/tokens.json"

IOS_TOKENS = ROOT / "apps/ios/SharedAutofill/QasaTokens.swift"
IOS_PALETTE = ROOT / "apps/ios/qasa_ios/Theme/ThemePalette+Tokens.swift"
ANDROID = ROOT / "apps/android/app/src/main/java/alibarznji/qasa/theme/QasaTokens.kt"
CSS = ROOT / "apps/desktop/src/theme/tokens.css"

HEADER = "Generated by design/generate.py from design/tokens.json. Do not edit."

# iOS easing curves as CSS / Compose cubic beziers.
CURVES = {
    "easeOut": (0.0, 0.0, 0.58, 1.0),
    "easeInOut": (0.42, 0.0, 0.58, 1.0),
    "easeIn": (0.42, 0.0, 1.0, 1.0),
    "linear": (0.0, 0.0, 1.0, 1.0),
}

SWIFT_WEIGHT = {400: ".regular", 500: ".medium", 600: ".semibold", 700: ".bold"}
KOTLIN_WEIGHT = {400: "FontWeight.Normal", 500: "FontWeight.Medium", 600: "FontWeight.SemiBold", 700: "FontWeight.Bold"}


def load() -> dict:
    spec = json.loads(SPEC.read_text(encoding="utf-8"))
    light, dark = spec["color"]["light"], spec["color"]["dark"]
    if list(light) != list(dark):
        raise SystemExit("light and dark palettes must list the same tokens in the same order")
    for scheme in (light, dark):
        for name, value in scheme.items():
            if not re.fullmatch(r"[0-9A-Fa-f]{6}", value):
                raise SystemExit(f"color {name}: {value!r} is not RRGGBB")
    for style, v in spec["type"]["styles"].items():
        if v["weight"] not in SWIFT_WEIGHT:
            raise SystemExit(f"type style {style}: weight {v['weight']} is not 400/500/600/700")
    return spec


def plain(group: dict) -> dict:
    return {k: v for k, v in group.items() if not k.startswith("$")}


def kebab(name: str) -> str:
    return re.sub(r"(?<!^)(?=[A-Z])", "-", name).lower()


def num(v: float) -> str:
    return str(int(v)) if float(v).is_integer() else repr(float(v))


def upper_snake(name: str) -> str:
    return re.sub(r"(?<!^)(?=[A-Z])", "_", name).upper()


# MARK: - Swift


def swift_tokens(spec: dict) -> str:
    out = [
        f"// {HEADER}",
        "// swiftlint:disable all",
        "",
        "import SwiftUI",
        "",
        "/// Every size, radius, gap, type style and timing the apps share (`design/tokens.json`).",
        "/// Android (`QasaTokens.kt`) and the desktop (`tokens.css`) get the same values.",
        "enum QasaTokens {",
    ]

    def cg_group(name: str, values: dict) -> None:
        out.append(f"    enum {name} {{")
        out.extend(f"        static let {k}: CGFloat = {num(v)}" for k, v in plain(values).items())
        out.append("    }")
        out.append("")

    cg_group("Radius", spec["radius"])
    cg_group("Size", spec["size"])
    cg_group("Space", spec["space"])

    t = spec["type"]
    out += [
        "    /// One text style: IBM Plex Sans Arabic at `size`, `weight`; line height is the font's own.",
        "    struct TextStyle: Equatable {",
        "        let size: CGFloat",
        "        let weight: Font.Weight",
        "    }",
        "",
        "    enum Typography {",
        f"        static let lineHeightMultiple: CGFloat = {num(t['lineHeight'])}",
    ]
    out += [
        f"        static let {k} = TextStyle(size: {num(v['size'])}, weight: {SWIFT_WEIGHT[v['weight']]})"
        for k, v in t["styles"].items()
    ]
    out += ["    }", ""]

    m = plain(spec["motion"])
    out.append("    enum Motion {")
    for k, v in m.items():
        if isinstance(v, dict) and "duration" in v:
            out.append(f"        static let {k}: Animation = .{v['curve']}(duration: {num(v['duration'])})")
            out.append(f"        static let {k}Duration: Double = {num(v['duration'])}")
        elif isinstance(v, dict):
            out.append(
                f"        static let {k}: Animation = .spring(response: {num(v['response'])}, "
                f"dampingFraction: {num(v['damping'])})"
            )
        else:
            out.append(f"        static let {k}: Double = {num(v)}")
    out += ["    }", ""]

    out.append("    enum Shadow {")
    for k, v in spec["shadow"].items():
        out.append(
            f"        static let {k} = (color: Color(red: {int(v['color'][0:2], 16)} / 255, "
            f"green: {int(v['color'][2:4], 16)} / 255, blue: {int(v['color'][4:6], 16)} / 255)"
            f".opacity({num(v['opacity'])}), radius: CGFloat({num(v['radius'])}), "
            f"x: CGFloat({num(v['x'])}), y: CGFloat({num(v['y'])}))"
        )
    out += ["    }", ""]

    for scheme in ("light", "dark"):
        out.append(f"    /// {scheme.capitalize()} palette as 0xRRGGBB.")
        out.append(f"    enum {scheme.capitalize()} {{")
        out += [f"        static let {k}: UInt32 = 0x{v.upper()}" for k, v in spec["color"][scheme].items()]
        out.append("    }")
        if scheme == "light":
            out.append("")
    out += ["}", ""]
    return "\n".join(out)


def swift_palette(spec: dict) -> str:
    out = [
        f"// {HEADER}",
        "// swiftlint:disable all",
        "",
        "import SwiftUI",
        "",
        "extension ThemePalette {",
    ]
    for scheme in ("dark", "light"):
        out.append(f"    static let {scheme} = ThemePalette(")
        items = list(spec["color"][scheme].items())
        for i, (k, v) in enumerate(items):
            comma = "," if i < len(items) - 1 else ""
            out.append(f'        {k}: Color(hex: "{v.upper()}"){comma}')
        out.append("    )")
        if scheme == "dark":
            out.append("")
    out += ["}", ""]
    return "\n".join(out)


# MARK: - Kotlin


def kotlin(spec: dict) -> str:
    out = [
        f"// {HEADER}",
        "@file:Suppress(\"MagicNumber\", \"ktlint\")",
        "",
        "package alibarznji.qasa.theme",
        "",
        "import androidx.compose.animation.core.CubicBezierEasing",
        "import androidx.compose.animation.core.Easing",
        "import androidx.compose.ui.graphics.Color",
        "import androidx.compose.ui.text.font.FontWeight",
        "import androidx.compose.ui.unit.Dp",
        "import androidx.compose.ui.unit.TextUnit",
        "import androidx.compose.ui.unit.dp",
        "import androidx.compose.ui.unit.sp",
        "",
        "/** One text style: IBM Plex Sans Arabic at [size], [weight], line height [lineHeight] (the font's own, as on iOS). */",
        "data class QasaTokenText(val size: TextUnit, val weight: FontWeight, val lineHeight: TextUnit)",
        "",
        "/** A SwiftUI spring (`response`, `dampingFraction`) and its Compose equivalent. */",
        "data class QasaTokenSpring(val response: Float, val dampingFraction: Float) {",
        "    /** Compose `spring(stiffness = …)`: (2π / response)² for unit mass. */",
        "    val stiffness: Float get() = (2f * Math.PI.toFloat() / response).let { it * it }",
        "    /** Compose `spring(dampingRatio = …)`: the same ratio SwiftUI calls dampingFraction. */",
        "    val dampingRatio: Float get() = dampingFraction",
        "}",
        "",
        "/** One timed animation: [millis] long on [easing] (the iOS curve of the same name). */",
        "data class QasaTokenTween(val millis: Int, val easing: Easing)",
        "",
        "/**",
        " * Every size, radius, gap, type style and timing the apps share (`design/tokens.json`).",
        " * iOS (`QasaTokens.swift`) and the desktop (`tokens.css`) get the same values; 1pt = 1dp.",
        " */",
        "object QasaTokens {",
    ]

    def dp_group(name: str, values: dict) -> None:
        out.append(f"    object {name} {{")
        out.extend(f"        val {k}: Dp = {num(v)}.dp" for k, v in plain(values).items())
        out.append("    }")
        out.append("")

    dp_group("Radius", spec["radius"])
    dp_group("Size", spec["size"])
    dp_group("Space", spec["space"])

    t = spec["type"]
    lh = float(t["lineHeight"])
    out.append("    object Typography {")
    out.append(f"        const val LINE_HEIGHT_MULTIPLE: Float = {num(lh)}f")
    for k, v in t["styles"].items():
        out.append(
            f"        val {k} = QasaTokenText({num(v['size'])}.sp, {KOTLIN_WEIGHT[v['weight']]}, "
            f"{num(v['size'] * lh)}.sp)"
        )
    out += ["    }", ""]

    out.append("    object Easings {")
    for name, (a, b, c, d) in CURVES.items():
        out.append(f"        val {name}: Easing = CubicBezierEasing({a}f, {b}f, {c}f, {d}f)")
    out += ["    }", ""]

    out.append("    object Motion {")
    for k, v in plain(spec["motion"]).items():
        if isinstance(v, dict) and "duration" in v:
            out.append(
                f"        val {k} = QasaTokenTween({round(v['duration'] * 1000)}, Easings.{v['curve']})"
            )
        elif isinstance(v, dict):
            out.append(f"        val {k} = QasaTokenSpring({num(v['response'])}f, {num(v['damping'])}f)")
        elif k == "toastVisible":
            out.append(f"        const val toastVisibleMillis: Long = {round(v * 1000)}L")
        else:
            out.append(f"        const val {k}: Float = {num(v)}f")
    out += ["    }", ""]

    out.append("    object Shadow {")
    for k, v in spec["shadow"].items():
        out.append(f"        val {k}Color: Color = Color(0xFF{v['color'].upper()}).copy(alpha = {num(v['opacity'])}f)")
        out.append(f"        val {k}Radius: Dp = {num(v['radius'])}.dp")
        out.append(f"        val {k}OffsetX: Dp = {num(v['x'])}.dp")
        out.append(f"        val {k}OffsetY: Dp = {num(v['y'])}.dp")
    out += ["    }", ""]

    for scheme in ("light", "dark"):
        out.append(f"    object {scheme.capitalize()} {{")
        out += [f"        val {k}: Color = Color(0xFF{v.upper()})" for k, v in spec["color"][scheme].items()]
        out.append("    }")
        if scheme == "light":
            out.append("")
    out += ["}", ""]
    return "\n".join(out)


# MARK: - CSS


def css(spec: dict) -> str:
    t = spec["type"]
    root = [":root {"]
    for group, prefix in (("radius", "radius"), ("size", "size"), ("space", "space")):
        root += [f"  --{prefix}-{kebab(k)}: {num(v)}px;" for k, v in plain(spec[group]).items()]
    # Names the desktop already used before the shared spec.
    root += [
        f"  --corner-radius: {num(spec['radius']['card'])}px;",
        f"  --corner-radius-large: {num(spec['radius']['cardLarge'])}px;",
        f"  --screen-padding: {num(spec['space']['screenPadding'])}px;",
        "",
        f"  --font-family: '{t['family']}', system-ui, sans-serif;",
        f"  --line-height: {num(t['lineHeight'])};",
    ]
    for k, v in t["styles"].items():
        root.append(f"  --type-{kebab(k)}-size: {num(v['size'])}px;")
        root.append(f"  --type-{kebab(k)}-weight: {v['weight']};")
    root.append("")
    for name, (a, b, c, d) in CURVES.items():
        root.append(f"  --ease-{kebab(name)}: cubic-bezier({a}, {b}, {c}, {d});")
    for k, v in plain(spec["motion"]).items():
        if isinstance(v, dict) and "duration" in v:
            root.append(f"  --motion-{kebab(k)}: {round(v['duration'] * 1000)}ms var(--ease-{kebab(v['curve'])});")
            root.append(f"  --motion-{kebab(k)}-duration: {round(v['duration'] * 1000)}ms;")
        elif isinstance(v, dict):
            # CSS has no spring; the closest ease-out of the spring's settle time.
            root.append(f"  --motion-{kebab(k)}: {round(v['response'] * 1000)}ms cubic-bezier(0.2, 0.9, 0.3, 1);")
        elif k == "toastVisible":
            root.append(f"  --motion-toast-visible: {round(v * 1000)}ms;")
        else:
            root.append(f"  --motion-{kebab(k)}: {num(v)};")
    root.append("")
    for k, v in spec["shadow"].items():
        r, g, b = (int(v["color"][i : i + 2], 16) for i in (0, 2, 4))
        root.append(
            f"  --shadow-{kebab(k)}: {num(v['x'])}px {num(v['y'])}px {num(v['radius'] * 2)}px "
            f"rgba({r}, {g}, {b}, {num(v['opacity'])});"
        )
    root.append("}")

    def block(selector: str, scheme: str, indent: str = "") -> list[str]:
        lines = [f"{indent}{selector} {{", f"{indent}  color-scheme: {scheme};"]
        lines += [f"{indent}  --{kebab(k)}: #{v.upper()};" for k, v in spec["color"][scheme].items()]
        lines.append(f"{indent}}}")
        return lines

    out = [
        f"/* {HEADER} */",
        "",
        *root,
        "",
        *block(':root,\n:root[data-theme="light"]', "light"),
        "",
        *block(':root[data-theme="dark"]', "dark"),
        "",
        "@media (prefers-color-scheme: dark) {",
        *block(':root:not([data-theme="light"])', "dark", "  "),
        "}",
        "",
    ]
    return "\n".join(out)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--check", action="store_true", help="exit 1 if a generated file is stale")
    args = parser.parse_args()
    spec = load()
    outputs = {
        IOS_TOKENS: swift_tokens(spec),
        IOS_PALETTE: swift_palette(spec),
        ANDROID: kotlin(spec),
        CSS: css(spec),
    }
    stale = []
    for path, text in outputs.items():
        current = path.read_text(encoding="utf-8") if path.is_file() else None
        if current == text:
            continue
        if args.check:
            stale.append(path)
        else:
            path.write_text(text, encoding="utf-8")
            print(f"wrote {path.relative_to(ROOT)}")
    if stale:
        for path in stale:
            print(f"stale: {path.relative_to(ROOT)}", file=sys.stderr)
        print("run: python3 design/generate.py", file=sys.stderr)
        return 1
    if args.check:
        print("design tokens up to date")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
